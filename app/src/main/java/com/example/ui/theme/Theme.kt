package com.example.ui.theme

import android.os.Build
import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.dynamicDarkColorScheme
import androidx.compose.material3.dynamicLightColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.LocalContext

private val DarkColorScheme =
  darkColorScheme(
    primary = GeoPrimary,
    onPrimary = GeoOnPrimary,
    primaryContainer = GeoPrimaryContainer,
    onPrimaryContainer = GeoOnPrimaryContainer,
    secondary = GeoSecondary,
    onSecondary = GeoOnSecondary,
    secondaryContainer = GeoSecondaryContainer,
    onSecondaryContainer = GeoOnSecondaryContainer,
    background = GeoBackground,
    onBackground = GeoOnSecondaryContainer,
    surface = GeoSurface,
    onSurface = GeoOnSecondaryContainer,
    surfaceVariant = GeoSurface,
    onSurfaceVariant = GeoSecondary,
    outline = GeoOutline
  )

private val LightColorScheme = DarkColorScheme // Keep consistent Geometric dark premium aesthetic in both modes

@Composable
fun MyApplicationTheme(
  darkTheme: Boolean = true, // Force premium dark geometric theme by default
  dynamicColor: Boolean = false, // Disable system wallpaper dynamic coloring to preserve theme
  content: @Composable () -> Unit,
) {
  val colorScheme =
    when {
      dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
        val context = LocalContext.current
        if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
      }

      darkTheme -> DarkColorScheme
      else -> LightColorScheme
    }

  MaterialTheme(colorScheme = colorScheme, typography = Typography, content = content)
}
